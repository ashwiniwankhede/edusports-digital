// Pedagogy v1.0: IB does not tie phases to grades, so the tool uses this internal mapping
// (never shown to teachers). "More rigorous" steps up one phase, capped at Phase 4.
const GRADE_PHASE = { "Grade 1": 2, "Grade 2": 2, "Grade 3": 3, "Grade 4": 3, "Grade 5": 4 };
export function phaseFor(grade, rigorous = false) {
  const base = GRADE_PHASE[grade] || 2;
  return Math.min(4, base + (rigorous ? 1 : 0));
}

// Topics outside a primary PE lesson; kept in IB_PSPE but never sent to the model.
const OUT_OF_SCOPE = /puberty|sexual|substance|addict|harass|chemical changes/i;
const keep = (t) => !OUT_OF_SCOPE.test(t);

/** The IB frame for one phase, as prompt text: all four strands (pedagogy v1.0 §3). */
export function ibBrief(phase, { outcomes = true, understandings = true } = {}) {
  const p = String(phase);
  return Object.entries(IB_PSPE).map(([strand, s]) => [
    `${strand} — overall expectation (Phase ${p}): ${s.expectations[p].split(/(?<=\.)\s+/).filter(keep).join(" ")}`,
    `  Example concepts: ${s.concepts.filter(keep).join(", ")}`,
    understandings ? `  Example conceptual understandings:\n${s.understandings[p].filter(keep).map((u) => `  - ${u}`).join("\n")}` : "",
    outcomes ? `  Example learning outcomes (Learners…):\n${s.outcomes[p].filter(keep).map((o) => `  - ${o}`).join("\n")}` : "",
  ].filter(Boolean).join("\n")).join("\n");
}

const norm = (t) => String(t).toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
/** Keep only IB outcomes that really are in the continuums for this phase (no invented IB text). */
export function verifiedOutcomes(list, phase) {
  const known = Object.values(IB_PSPE).flatMap((s) => s.outcomes[String(phase)] || []).filter(keep);
  return (list || []).map((o) => known.find((k) => norm(k) === norm(o) || norm(o).includes(norm(k)) && norm(k).length > 20)).filter(Boolean)
    .filter((o, i, a) => a.indexOf(o) === i);
}

export const STRANDS = Object.keys(IB_PSPE);
